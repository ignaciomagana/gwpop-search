@dataclass(frozen=True)
class EvidenceCheckPassRule:
    """Pre-declared engineering pass rule of the Phase-3c evidence check."""

    FORMAT_VERSION: ClassVar[str] = "gwpop-search-phase3-evidence-check-rule-1.0"

    max_null_ln_bf: float = 3.0
    min_injected_ln_bf: float = 0.0
    sddr_tolerance_floor: float = 0.3
    sddr_tolerance_sigmas: float = 2.0
    expected_null_cases: int = 8
    expected_injected_cases: int = 2
    sigma_ns_kappa_hat: float = DEFAULT_SIGMA_NS_KAPPA_HAT
    fit_criteria: NSRecoveryAcceptanceCriteria = field(
        default_factory=NSRecoveryAcceptanceCriteria.f3_level
    )

    def __post_init__(self) -> None:
        for name in ("max_null_ln_bf", "min_injected_ln_bf"):
            if not math.isfinite(float(getattr(self, name))):
                raise ValueError(f"{name} must be finite")
        if not float(self.sddr_tolerance_floor) > 0.0:
            raise ValueError("sddr_tolerance_floor must be positive")
        if not float(self.sddr_tolerance_sigmas) > 0.0:
            raise ValueError("sddr_tolerance_sigmas must be positive")
        if not float(self.sigma_ns_kappa_hat) > 0.0:
            raise ValueError("sigma_ns_kappa_hat must be positive")
        for name in ("expected_null_cases", "expected_injected_cases"):
            if int(getattr(self, name)) < 0:
                raise ValueError(f"{name} cannot be negative")
        if not isinstance(self.fit_criteria, NSRecoveryAcceptanceCriteria):
            raise TypeError("fit_criteria must be NSRecoveryAcceptanceCriteria")

    @classmethod
    def for_plan(cls, *, n_catalogs: int, n_atoms: int, **overrides) -> "EvidenceCheckPassRule":
        """The rule of a check with ``n_catalogs`` catalogs and ``n_atoms`` atoms.

        The case counts are a property of the plan, not a constant: a check run
        with fewer catalogs must not fail on the count alone.
        """
        payload = {
            "expected_null_cases": int(n_catalogs) * int(n_atoms),
            "expected_injected_cases": int(n_atoms),
        }
        payload.update(overrides)
        return cls(**payload)

    def to_dict(self) -> dict[str, object]:
        payload: dict[str, object] = {"format_version": self.FORMAT_VERSION}
        for item in dataclass_fields(self):
            value = getattr(self, item.name)
            payload[item.name] = (
                value.to_dict() if isinstance(value, NSRecoveryAcceptanceCriteria) else value
            )
        return payload

    @classmethod
    def from_dict(cls, payload: Mapping[str, object]) -> "EvidenceCheckPassRule":
        values = dict(payload)
        version = values.pop("format_version", None)
        if version != cls.FORMAT_VERSION:
            raise ValueError(f"unsupported evidence-check rule format {version!r}")
        known = {item.name for item in dataclass_fields(cls)}
        unknown = sorted(set(values) - known)
        if unknown:
            raise ValueError(f"unknown evidence-check rule field(s) {unknown}")
        if "fit_criteria" in values:
            values["fit_criteria"] = NSRecoveryAcceptanceCriteria.from_dict(values["fit_criteria"])
        return cls(**values)


def _rule_check(name: str, value, limit, comparison: str, **extra) -> dict[str, object]:
    ok = value is not None and not isinstance(value, bool) and math.isfinite(float(value))
    if ok:
        value = float(value)
        passed = {
            "lt": value < float(limit),
            "gt": value > float(limit),
            "le": value <= float(limit),
            "ge": value >= float(limit),
            "eq": value == float(limit),
        }[comparison]
    else:
        passed = False
    record = {
        "name": name,
        "value": value if ok else None,
        "comparison": comparison,
        "limit": float(limit),
        "passed": bool(passed),
    }
    record.update(extra)
    return record


def evaluate_evidence_check_rule(
    null_cases: Sequence[Mapping[str, object]],
    injected_cases: Sequence[Mapping[str, object]],
    fit_assessments: Sequence[Mapping[str, object]],
    rule: EvidenceCheckPassRule | None = None,
) -> dict[str, object]:
    """Apply the pre-declared pass rule.

    ``null_cases``/``injected_cases`` need ``catalog``, ``atom``, ``ln_bf`` and
    ``ln_bf_sigma``; null cases also ``sddr["ln_bf"]`` and, for the full
    tolerance of MODEL_COMPARISON_MATH.md 9.1(8), ``sddr["bootstrap_std"]``.
    ``fit_assessments`` are :func:`assess_ns_fit` results (with a ``passed``
    flag) of every fit.

    The SDDR tolerance is ``max(floor, sigmas * sqrt(sigma^2 +
    sigma_SDDR^2))``. A missing ``sigma`` fails the check (the tolerance is
    then undefined); a missing ``sigma_SDDR`` only drops that term, which makes
    the tolerance tighter, and is recorded in a note.
    """
    rule = EvidenceCheckPassRule() if rule is None else rule
    null_cases = [dict(case) for case in null_cases]
    injected_cases = [dict(case) for case in injected_cases]
    n_fits = len(fit_assessments)
    n_valid = sum(bool(item["passed"]) for item in fit_assessments)
    checks = [
        {
            "name": "all_fits_numerically_valid",
            "value": f"{n_valid}/{n_fits}",
            "comparison": "all",
            "limit": "F3-level gates",
            "passed": bool(n_fits > 0 and n_valid == n_fits),
        },
        _rule_check("n_null_cases", len(null_cases), rule.expected_null_cases, "eq"),
        _rule_check("n_injected_cases", len(injected_cases), rule.expected_injected_cases, "eq"),
    ]
    for case in null_cases:
        label = f"null.{case['catalog']}.{case['atom']}"
        checks.append(_rule_check(f"{label}.ln_bf", case.get("ln_bf"), rule.max_null_ln_bf, "lt"))
    for case in injected_cases:
        label = f"injected.{case['atom']}"
        checks.append(
            _rule_check(f"{label}.ln_bf", case.get("ln_bf"), rule.min_injected_ln_bf, "gt")
        )
    for case in null_cases:
        label = f"null.{case['catalog']}.{case['atom']}"
        sigma = _finite_or_none(case.get("ln_bf_sigma"))
        sddr = dict(case.get("sddr") or {})
        sigma_sddr = _finite_or_none(sddr.get("bootstrap_std"))
        difference = None
        if case.get("ln_bf") is not None and sddr.get("ln_bf") is not None:
            difference = abs(float(case["ln_bf"]) - float(sddr["ln_bf"]))
        floor = float(rule.sddr_tolerance_floor)
        # MODEL_COMPARISON_MATH.md 9.1(8):
        # |ln BF_NS - ln BF_SDDR| <= 2 sqrt(sigma_NS,a^2/R_a + sigma_NS,b^2/R_b + sigma_SDDR^2).
        combined = (
            None
            if sigma is None
            else math.sqrt(sigma**2 + (0.0 if sigma_sddr is None else sigma_sddr**2))
        )
        tolerance = (
            floor
            if combined is None
            else max(floor, float(rule.sddr_tolerance_sigmas) * combined)
        )
        record = _rule_check(
            f"{label}.sddr_agreement",
            difference,
            tolerance,
            "le",
            ln_bf_sigma=sigma,
            sddr_bootstrap_std=sigma_sddr,
            combined_sigma=combined,
        )
        if sigma is None:
            record["passed"] = False
            record["note"] = "ln BF sigma unavailable"
        elif sigma_sddr is None:
            record["note"] = "SDDR bootstrap std unavailable; tolerance omits sigma_SDDR"
        checks.append(record)
    return {
        "rule": rule.to_dict(),
        "passed": bool(all(item["passed"] for item in checks)),
        "checks": checks,
    }


