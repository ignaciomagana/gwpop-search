def root_equivalence_check(
    posterior,
    selection,
    *,
    seed: int,
    truth: Mapping[str, float] | None = None,
    n_prior_draws: int = ROOT_EQUIVALENCE_PRIOR_DRAWS,
    atol: float = ROOT_EQUIVALENCE_ATOL,
) -> dict[str, object]:
    """Compare ``compile_model_spec(baseline_model_spec())`` with ``GwcatChiEffBBHModel``.

    Both densities are evaluated on every PE and selection sample at the
    truth (default: the Phase-3 truth) and at ``n_prior_draws`` seeded draws
    of the root hyperprior. Passes iff the priors are identical, the support
    (finite vs ``-inf``) agrees everywhere, no value is NaN/+inf and every
    finite difference is at most ``atol``.
    """
    from gwpop_search.grammar import baseline_model_spec
    from gwpop_search.models import (
        DEFAULT_BASELINE_HYPERPARAMETERS,
        GwcatChiEffBBHModel,
        compile_model_spec,
    )

    from .model_spec import prior_specs_from_model_spec
    from .priors import BASELINE_SYNTHETIC_PRIORS

    spec = baseline_model_spec()
    declarative = compile_model_spec(spec)
    reference = GwcatChiEffBBHModel()
    priors = prior_specs_from_model_spec(spec)
    priors_equal = priors == dict(BASELINE_SYNTHETIC_PRIORS)
    context_equal = all(
        declarative.to_config()[key] == reference.to_config()[key]
        for key in ("cosmology", "zmax", "q_floor", "redshift_quadrature_order")
    )
    names, transform = prior_transform_for(priors)
    rng = np.random.default_rng(int(seed))
    truth = dict(DEFAULT_BASELINE_HYPERPARAMETERS if truth is None else truth)
    points = [{name: float(truth[name]) for name in names}]
    for _ in range(int(n_prior_draws)):
        values = transform(rng.random(len(names)))
        points.append({name: float(values[k]) for k, name in enumerate(names)})
    blocks = {"pe": posterior.samples, "selection": selection.samples}
    max_abs = 0.0
    n_values = 0
    n_finite = 0
    support_mismatches = 0
    invalid_values = 0
    for hp in points:
        for samples in blocks.values():
            a = np.asarray(declarative(samples, hp), dtype=np.float64)
            b = np.asarray(reference(samples, hp), dtype=np.float64)
            if a.shape != b.shape:
                raise RuntimeError(f"density shapes differ: {a.shape} vs {b.shape}")
            invalid_values += int(np.count_nonzero(np.isnan(a) | np.isposinf(a)))
            invalid_values += int(np.count_nonzero(np.isnan(b) | np.isposinf(b)))
            finite_a = np.isfinite(a)
            finite_b = np.isfinite(b)
            support_mismatches += int(np.count_nonzero(finite_a != finite_b))
            both = finite_a & finite_b
            n_values += int(a.size)
            n_finite += int(np.count_nonzero(both))
            if both.any():
                max_abs = max(max_abs, float(np.max(np.abs(a[both] - b[both]))))
    passed = bool(
        priors_equal
        and context_equal
        and support_mismatches == 0
        and invalid_values == 0
        and max_abs <= float(atol)
    )
    return {
        "declarative_model_hash": spec.model_hash,
        "n_points": len(points),
        "n_values": n_values,
        "n_finite": n_finite,
        "priors_equal": bool(priors_equal),
        "context_equal": bool(context_equal),
        "support_mismatches": support_mismatches,
        "nan_or_posinf_values": invalid_values,
        "max_abs_difference": max_abs,
        "atol": float(atol),
        "passed": passed,
    }


def _pooled_weighted_parameter(results: Sequence[DynestyResult], index: int):
    """Dead + final live points of every run, each run's weights normalized to 1/R."""
    values, weights = [], []
    for result in results:
        w = np.asarray(result.weights, dtype=float)
        values.append(np.asarray(result.samples, dtype=float)[:, index])
        weights.append(w / (np.sum(w) * len(results)))
    return np.concatenate(values), np.concatenate(weights)


def _kde_log_density(values, weights, at: float):
    from scipy.stats import gaussian_kde

    keep = weights > 0.0
    kde = gaussian_kde(values[keep], weights=weights[keep])
    density = float(kde(np.asarray([float(at)]))[0])
    bandwidth = float(np.sqrt(kde.covariance[0, 0]))
    return (math.log(density) if density > 0.0 else float("-inf")), bandwidth, float(kde.neff)


def savage_dickey_ln_bf(
    results: Sequence[DynestyResult],
    parameter: str,
    prior: PriorSpec,
    *,
    null_value: float = 0.0,
    n_bootstrap: int = DEFAULT_SDDR_BOOTSTRAP,
    seed: int,
) -> dict[str, object]:
    """Savage-Dickey ``ln BF(child/root) = ln pi(null) - ln p(null | D)``.

    ``p(null | D)`` is a Gaussian KDE (``scipy.stats.gaussian_kde``, Scott's
    rule with the Kish size) of the child's marginal posterior of
    ``parameter``, built from the weighted dead and final live points of all
    runs, each run normalized to weight ``1/R`` (the equal-weight mixture of
    the runs). No boundary correction is applied: ``null`` must lie strictly
    inside a uniform prior. ``bootstrap_std`` is the standard deviation of the
    estimate over ``n_bootstrap`` resamplings (with replacement, within each
    run) of the weighted points.
    """
    results = list(results)
    names = _common_names(results)
    if parameter not in names:
        raise ValueError(f"{parameter!r} is not a parameter of the runs {names}")
    if prior.family != "uniform":
        raise ValueError("the Savage-Dickey check is implemented for uniform slope priors")
    if not float(prior.low) < float(null_value) < float(prior.high):
        raise ValueError("the null value must lie strictly inside the prior (no reflection)")
    index = names.index(parameter)
    ln_prior = -math.log(float(prior.high) - float(prior.low))
    values, weights = _pooled_weighted_parameter(results, index)
    ln_density, bandwidth, neff = _kde_log_density(values, weights, null_value)
    mean = float(np.sum(weights * values))
    std = float(np.sqrt(np.sum(weights * (values - mean) ** 2)))
    rng = np.random.default_rng(int(seed))
    boot = []
    for _ in range(int(n_bootstrap)):
        v_b, w_b = [], []
        for result in results:
            samples = np.asarray(result.samples, dtype=float)[:, index]
            w = np.asarray(result.weights, dtype=float)
            pick = rng.integers(0, samples.size, samples.size)
            total = float(np.sum(w[pick]))
            if total <= 0.0:
                continue
            v_b.append(samples[pick])
            w_b.append(w[pick] / (total * len(results)))
        if len(v_b) != len(results):
            continue
        ln_b, _, _ = _kde_log_density(np.concatenate(v_b), np.concatenate(w_b), null_value)
        if math.isfinite(ln_b):
            boot.append(ln_prior - ln_b)
    ln_bf = ln_prior - ln_density if math.isfinite(ln_density) else None
    return {
        "parameter": parameter,
        "null_value": float(null_value),
        "prior": prior.to_dict(),
        "ln_prior_density": ln_prior,
        "ln_posterior_density": _finite_or_none(ln_density),
        "ln_bf": _finite_or_none(ln_bf),
        "bootstrap_std": float(np.std(boot, ddof=1)) if len(boot) > 1 else None,
        "n_bootstrap": len(boot),
        "kde": "scipy.stats.gaussian_kde (Scott's rule, NS weights, runs pooled with equal weight)",
        "bandwidth": bandwidth,
        "n_effective": neff,
        "posterior_mean": mean,
        "posterior_std": std,
        "posterior_mass_above_null": float(np.sum(weights[values > float(null_value)])),
    }


