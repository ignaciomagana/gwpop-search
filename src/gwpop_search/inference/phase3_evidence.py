"""Phase 3c: Bayes-factor sanity mini-campaign on synthetic catalogs.

Format ``gwpop-search-phase3-evidence-check-1.0``. It checks, on catalogs whose
answer is known, that the dynesty evidence pipeline gives sensible Bayes
factors for two exactly nested atoms of the model graph:

* ``chieff.mean.linear_q`` adds ``chi_mu_q_slope`` ~ U(-0.6, 0.6), pivot 0.7;
* ``pairing.beta.linear_m1`` adds ``beta_q_m1_slope`` ~ U(-0.3, 0.3), pivot 30.

Both children equal the root at slope 0 and the child's conditional prior of
the shared parameters is the root prior, so the Savage-Dickey density ratio is
exact (Verdinelli-Wasserman factor 1; design/MODEL_COMPARISON_MATH.md, Sec. 2
and 4).

Design (pre-declared and recorded in the plan)
----------------------------------------------
(a) Null cases: the ``n_catalogs`` Phase-3 v2 catalogs (the recovery
    campaign's seed pairs and survey, generated from the root truth). On each:
    F3-style evidence (``R`` independent dynesty runs, the campaign's dynesty
    settings with ``slices = 2 * (3 + ndim)`` of each model) for the
    declarative root ``compile_model_spec(baseline_model_spec())`` and for both
    children (the registered mutation applied to the root). Reported:
    ``ln BF(child/root) = mean lnZ_child - mean lnZ_root`` with, per
    MODEL_COMPARISON_MATH.md 9.1(6),
    ``sigma^2 = sigma_NS,child^2 / R_child + sigma_NS,root^2 / R_root``,
    ``sigma_NS,M = max(repeat std, mean logzerr, kappa_hat sqrt(H_M / nlive))``,
    and the Savage-Dickey cross-check ``ln BF_SDDR = ln pi(0) - ln p(0 | D)``
    (NS-weighted Gaussian KDE of the child's pooled slope posterior at 0; no
    reflection, 0 is interior). The Monte-Carlo-likelihood term ``sigma_MC,ab``
    of 9.1(6) is not computed here; it is common to both routes and so does not
    belong in the SDDR tolerance (design Sec. 4.4), but the reported
    ``ln_bf_sigma`` is consequently a nested-sampling-only uncertainty and a
    lower bound on the full 9.1(6) error. The literal formula of the original
    task text, ``sqrt(cons_child^2 + cons_root^2)`` with ``cons = max(repeat
    std, max reported error)``, is recorded beside it as
    ``ln_bf_sigma_task_text``: it is the error of a single run rather than of
    the mean of ``R``, i.e. larger by about ``sqrt(R)``, and no check uses it.
(b) Injected cases: one catalog per atom drawn from the child model with the
    slope at ``0.9 x`` the upper prior bound (0.54 and 0.27) and every other
    hyperparameter at the root truth, generated by the DAG-consistent
    structured generator :func:`gwpop_search.scouts.synthetic.generate_structured_scout_dataset`
    (it honours ``observation_model="noisy_observation"``: one noise
    realisation per system, detection on observed data, PE drawn given the
    observation). Root and child evidence as in (a).

Before any fit, ``compile_model_spec(baseline_model_spec())`` and
``GwcatChiEffBBHModel`` are compared on every catalog's PE and selection
samples at the truth and at seeded prior draws (identical support and
``|delta log p| <= 1e-10``); a mismatch aborts the check.

Engineering pass rule (:class:`EvidenceCheckPassRule`)
-----------------------------------------------------
1. every fit is numerically valid under the F3-level gates
   (:meth:`NSRecoveryAcceptanceCriteria.f3_level`);
2. ``ln BF(child/root) < 3`` in all ``8`` null cases (4 catalogs x 2 atoms);
3. ``ln BF(child/root) > 0`` in both injected cases;
4. ``|ln BF - ln BF_SDDR| <= max(0.3, 2 sqrt(sigma^2 + sigma_SDDR^2))`` in
   every null case (MODEL_COMPARISON_MATH.md 9.1(8); ``sigma_SDDR`` is the
   bootstrap standard deviation of the Savage-Dickey estimate).

The expected case counts of items 2 and 3 follow the plan: ``n_catalogs x
len(atoms)`` null cases and ``len(atoms)`` injected ones.

Injection strengths: the conditional profile likelihood of each slope (other
hyperparameters at the truth, the partner intercept profiled) on 48-event v2
catalogs drawn from the child model gave slope widths of about 0.18
(``chi_mu_q_slope``) and 0.04-0.09 (``beta_q_m1_slope``, growing with the
slope). Its approximation of ``ln BF`` was positive in every probed catalog:
0.54-4.97 at ``chi_mu_q_slope = 0.55`` (9 catalogs) and 0.51-9.73 at
``beta_q_m1_slope = 0.25`` and 0.3 (6 and 9 catalogs)
(gwpop-search-data/validation/phase3c_injection_strength_probe/). The marginal
evidence is lower than this conditional approximation, so the injected cases
are a weak check of power, not of calibration.
"""

