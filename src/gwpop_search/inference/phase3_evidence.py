def _mutations_by_id():
    from gwpop_search.grammar import DEFAULT_MUTATIONS

    return {mutation.mutation_id: mutation for mutation in DEFAULT_MUTATIONS}


def _validated_atoms(atoms: Sequence[str]) -> tuple[str, ...]:
    atoms = tuple(str(atom) for atom in atoms)
    if not atoms:
        raise ValueError("at least one atom is required")
    if len(set(atoms)) != len(atoms):
        raise ValueError(f"atoms must be unique; got {atoms}")
    unknown = sorted(set(atoms) - set(ATOM_SLOPE_PARAMETERS))
    if unknown:
        raise ValueError(
            f"unsupported atom(s) {unknown}; the evidence check covers {EVIDENCE_CHECK_ATOMS}"
        )
    return atoms


def atom_slope_prior(atom: str) -> PriorSpec:
    """The registered child prior of ``atom``'s slope (a ``PriorSpec``)."""
    mutation = _mutations_by_id()[atom]
    prior = mutation.prior_updates[ATOM_SLOPE_PARAMETERS[atom]]
    return PriorSpec(prior.family, **dict(prior.parameters))


def default_injection_strengths(atoms: Sequence[str] = EVIDENCE_CHECK_ATOMS) -> dict[str, float]:
    """``0.9 x`` the upper bound of each atom's registered slope prior (0.54, 0.27)."""
    out = {}
    for atom in _validated_atoms(atoms):
        prior = atom_slope_prior(atom)
        out[atom] = round(INJECTION_FRACTION_OF_UPPER_BOUND * float(prior.high), 12)
    return out


def evidence_check_model_specs(atoms: Sequence[str] = EVIDENCE_CHECK_ATOMS):
    """``{"root": baseline_model_spec(), atom: registered mutation applied to the root}``."""
    from gwpop_search.grammar import apply_mutation, baseline_model_spec

    atoms = _validated_atoms(atoms)
    root = baseline_model_spec()
    mutations = _mutations_by_id()
    specs = {ROOT_LABEL: root}
    for atom in atoms:
        child = apply_mutation(root, mutations[atom])
        added = sorted(set(child.priors) - set(root.priors))
        if added != [ATOM_SLOPE_PARAMETERS[atom]] or set(root.priors) - set(child.priors):
            raise RuntimeError(f"{atom} is not the nested one-slope extension of the root")
        specs[atom] = child
    return specs


