def generate_injected_catalog(*, atom: str, strength: float, data_seed: int, survey_config):
    """A catalog drawn from ``atom``'s child model (slope ``strength``, root truth otherwise).

    Uses the grammar-matched structured generator
    :func:`gwpop_search.scouts.synthetic.generate_structured_scout_dataset`,
    which draws the events from the child population and then applies the
    survey's own observation model through the Phase-3 synthetic machinery
    (``noisy_observation``: one noise realisation per event and injection,
    detection on the observed data, PE drawn given the observation; the
    selection injections are the survey's baseline-proxy draws). The
    structured draw density equals the compiled child density
    (``tests/test_phase3_evidence_check.py``).
    """
    from gwpop_search.scouts.synthetic import (
        StructuredScoutInjection,
        generate_structured_scout_dataset,
    )

    from .synthetic import OBSERVATION_MODEL_NOISY

    atom = _validated_atoms([atom])[0]
    dataset = generate_structured_scout_dataset(
        seed=int(data_seed),
        injection=StructuredScoutInjection(atom, float(strength)),
        survey_config=survey_config,
    )
    noisy = survey_config.observation_model == OBSERVATION_MODEL_NOISY
    if noisy and dataset.event_observations is None:  # pragma: no cover - generator contract
        raise RuntimeError("structured generator ignored observation_model='noisy_observation'")
    parameter = ATOM_SLOPE_PARAMETERS[atom]
    if float(dataset.truth_hyperparameters[parameter]) != float(strength):
        raise RuntimeError(f"injected catalog does not record {parameter}={strength}")
    return dataset


def _model_dynesty_config(base: DynestyConfig, ndim: int, slices_rule: str) -> DynestyConfig:
    if slices_rule == SLICES_RULE_PER_MODEL:
        if base.sample not in ("slice", "rslice"):
            raise ValueError("the per-model slices rule needs sample='slice' or 'rslice'")
        return replace(base, slices=slices_for_ndim(ndim))
    if slices_rule == SLICES_RULE_FIXED:
        return base
    raise ValueError(f"unknown slices rule {slices_rule!r}")


def _fit_seed(sampler_seed: int, model_hash: str, repeat: int) -> int:
    return _derived_seed(int(sampler_seed), f"evidence-check:{model_hash}", int(repeat))


def build_evidence_check_plan(
    *,
    n_catalogs: int,
    root_seed: int,
    repeats: int,
    survey_config,
    dynesty_config: DynestyConfig,
    slices_rule: str,
    hbi_config,
    atoms: Sequence[str],
    injection_strengths: Mapping[str, float],
    rule: EvidenceCheckPassRule,
    importance_draws: int = DEFAULT_IMPORTANCE_DRAWS,
    rhat_draws_per_run: int = DEFAULT_RHAT_DRAWS_PER_RUN,
    sddr_bootstrap: int = DEFAULT_SDDR_BOOTSTRAP,
) -> dict[str, object]:
    """The ``gwpop-search-phase3-evidence-check-plan-1.0`` payload (JSON-normalized)."""
    from gwpop_search.models import DEFAULT_BASELINE_HYPERPARAMETERS

    from .model_spec import prior_specs_from_model_spec

    atoms = _validated_atoms(atoms)
    n_catalogs = int(n_catalogs)
    if n_catalogs < 1:
        raise ValueError("n_catalogs must be positive")
    repeats = int(repeats)
    if repeats < 2:
        raise ValueError("repeats must be >= 2")
    if set(injection_strengths) != set(atoms):
        raise ValueError("injection_strengths must give exactly one strength per atom")
    specs = evidence_check_model_specs(atoms)
    models = {}
    for label, spec in specs.items():
        priors = prior_specs_from_model_spec(spec)
        models[label] = {
            "model_hash": spec.model_hash,
            "mutation_id": None if label == ROOT_LABEL else label,
            "ndim": len(priors),
            "priors": serialize_prior_map(priors),
            "dynesty_config": plan_dynesty_config(
                _model_dynesty_config(dynesty_config, len(priors), slices_rule)
            ),
        }
    injected = []
    for atom in atoms:
        strength = float(injection_strengths[atom])
        prior = atom_slope_prior(atom)
        if not float(prior.low) <= strength <= float(prior.high):
            raise ValueError(f"injection strength {strength} of {atom} lies outside its prior")
        injected.append(
            {
                "atom": atom,
                "parameter": ATOM_SLOPE_PARAMETERS[atom],
                "strength": strength,
                "data_seed": _derived_seed(
                    int(root_seed), f"evidence-check-injection-data:{atom}", 0
                ),
                "sampler_seed": _derived_seed(
                    int(root_seed), f"evidence-check-injection-sampler:{atom}", 0
                ),
            }
        )
    plan = {
        "format_version": EVIDENCE_CHECK_PLAN_FORMAT_VERSION,
        "root_seed": int(root_seed),
        "n_catalogs": n_catalogs,
        "repeats": repeats,
        "atoms": list(atoms),
        "catalogs": [
            {"label": f"catalog_{i:03d}", "data_seed": int(data), "sampler_seed": int(sampler)}
            for i, (data, sampler) in enumerate(
                recovery_seed_pairs(n_catalogs, root_seed=int(root_seed))
            )
        ],
        "injected": injected,
        "injection_rule": f"slope = {INJECTION_FRACTION_OF_UPPER_BOUND} x upper prior bound "
        "unless overridden; other hyperparameters at the root truth",
        "survey_config": survey_config.to_dict(),
        "hbi_config": _hbi_config_payload(hbi_config),
        "dynesty_config_base": plan_dynesty_config(dynesty_config),
        "slices_rule": slices_rule,
        "models": models,
        "truth_hyperparameters": {
            name: float(value) for name, value in DEFAULT_BASELINE_HYPERPARAMETERS.items()
        },
        "diagnostics": {
            "importance_draws": int(importance_draws),
            "rhat_draws_per_run": int(rhat_draws_per_run),
            "sddr_bootstrap": int(sddr_bootstrap),
            "root_equivalence": {
                "atol": ROOT_EQUIVALENCE_ATOL,
                "n_prior_draws": ROOT_EQUIVALENCE_PRIOR_DRAWS,
            },
        },
        "rule": rule.to_dict(),
    }
    return json.loads(json.dumps(plan, sort_keys=True))


def _run_fit(
    fit_dir: Path,
    dataset,
    spec,
    *,
    label: str,
    sampler_seed: int,
    repeats: int,
    config: DynestyConfig,
    hbi_config,
    importance_draws: int,
    rhat_draws_per_run: int,
):
    from gwpop_search.models import compile_model_spec

    from .model_spec import prior_specs_from_model_spec
    from .synthetic import require_population_proxy_coverage

    model = compile_model_spec(spec)
    priors = prior_specs_from_model_spec(spec)
    require_population_proxy_coverage(
        dataset.selection, priors=priors, context=f"Phase-3c evidence check, {label}"
    )
    seeds = [_fit_seed(sampler_seed, spec.model_hash, r) for r in range(int(repeats))]
    results = []
    run_dirs = []
    for r, seed in enumerate(seeds):
        relative = f"repeat_{r:03d}"
        results.append(
            run_dynesty_population(
                dataset.posterior,
                dataset.selection,
                model,
                priors,
                seed=int(seed),
                config=config,
                hbi_config=hbi_config,
                run_dir=fit_dir / relative,
            )
        )
        run_dirs.append(relative)
    fit = summarize_ns_fit(
        results,
        dataset.posterior,
        dataset.selection,
        model,
        hbi_config=hbi_config,
        importance_draws=importance_draws,
        importance_seed=_derived_seed(
            int(sampler_seed), f"evidence-check-importance:{spec.model_hash}", 0
        ),
        rhat_draws_per_run=rhat_draws_per_run,
        run_dirs=run_dirs,
    )
    payload = {
        "format_version": NS_FIT_SUMMARY_FORMAT_VERSION,
        "label": label,
        "model_hash": spec.model_hash,
        "repeat_seeds": seeds,
        "dynesty_config": plan_dynesty_config(config),
        "fit": fit,
    }
    _atomic_write_json(fit_dir / FIT_SUMMARY_NAME, payload)
    return results, payload


def ln_bf_sigma_ns(
    child_evidence: Mapping[str, object],
    root_evidence: Mapping[str, object],
    *,
    kappa_hat: float = DEFAULT_SIGMA_NS_KAPPA_HAT,
) -> dict[str, object]:
    """``sigma(ln BF)`` from nested sampling, MODEL_COMPARISON_MATH.md 9.1(6).

    ``sigma^2 = sigma_NS,child^2 / R_child + sigma_NS,root^2 / R_root``. The
    Monte-Carlo-likelihood term ``sigma_MC,ab^2`` of 9.1(6) is not computed by
    this module (it needs the posterior-averaged normalized weights of both
    models) and is not included; the result is therefore a nested-sampling-only
    error. It is the right quantity for the SDDR cross-check (9.1(8)), whose
    two routes share the same Monte-Carlo likelihood (design Sec. 4.4).
    """
    child = ns_evidence_sigma(child_evidence, kappa_hat=kappa_hat)
    root = ns_evidence_sigma(root_evidence, kappa_hat=kappa_hat)
    means = (child["sigma_of_mean"], root["sigma_of_mean"])
    sigma = None if any(value is None for value in means) else float(math.hypot(*means))
    return {
        "formula": "MODEL_COMPARISON_MATH.md 9.1(6), sigma_MC term not included",
        "sigma": sigma,
        "child": child,
        "root": root,
        "includes_sigma_mc": False,
    }


def _bayes_factor_case(
    *,
    kind: str,
    catalog: str,
    atom: str,
    root_fit: Mapping[str, object],
    child_fit: Mapping[str, object],
    child_results: Sequence[DynestyResult],
    sddr_seed: int,
    sddr_bootstrap: int,
    kappa_hat: float = DEFAULT_SIGMA_NS_KAPPA_HAT,
    truth_slope: float | None = None,
) -> dict[str, object]:
    root_evidence = dict(dict(root_fit["fit"])["evidence"])
    child_evidence = dict(dict(child_fit["fit"])["evidence"])
    ln_bf = float(child_evidence["mean"]) - float(root_evidence["mean"])
    budget = ln_bf_sigma_ns(child_evidence, root_evidence, kappa_hat=kappa_hat)
    sigma = budget["sigma"]
    errors = (child_evidence.get("conservative_error"), root_evidence.get("conservative_error"))
    sigma_task_text = None if any(e is None for e in errors) else float(math.hypot(*errors))
    parameter = ATOM_SLOPE_PARAMETERS[atom]
    sddr = savage_dickey_ln_bf(
        child_results,
        parameter,
        atom_slope_prior(atom),
        n_bootstrap=sddr_bootstrap,
        seed=sddr_seed,
    )
    case = {
        "kind": kind,
        "catalog": catalog,
        "atom": atom,
        "parameter": parameter,
        "root_model_hash": root_fit["model_hash"],
        "child_model_hash": child_fit["model_hash"],
        "data_identity": dict(root_fit["fit"])["data_identity"],
        "root_log_evidence": float(root_evidence["mean"]),
        "root_conservative_error": errors[1],
        "child_log_evidence": float(child_evidence["mean"]),
        "child_conservative_error": errors[0],
        "ln_bf": ln_bf,
        "ln_bf_sigma": sigma,
        "ln_bf_sigma_budget": budget,
        # The literal formula of the original task text: the single-run error,
        # not the error of the mean of R runs. Recorded for traceability; no
        # check uses it.
        "ln_bf_sigma_task_text": sigma_task_text,
        "sddr": sddr,
        "ln_bf_minus_sddr": None if sddr["ln_bf"] is None else ln_bf - float(sddr["ln_bf"]),
    }
    if truth_slope is not None:
        names = _common_names(child_results)
        draws = np.concatenate([np.asarray(r.posterior_samples, float) for r in child_results])
        values = draws[:, names.index(parameter)]
        q05, q50, q95 = np.quantile(values, [0.05, 0.5, 0.95])
        case["injected_slope"] = float(truth_slope)
        case["slope_posterior"] = {
            "q05": float(q05),
            "median": float(q50),
            "q95": float(q95),
            "truth_in_90pct_interval": bool(q05 <= truth_slope <= q95),
        }
    return case


def run_evidence_check(
    root: str | Path,
    *,
    n_catalogs: int = 4,
    root_seed: int = PHASE3_ROOT_SEED,
    repeats: int = 2,
    survey_config=None,
    dynesty_config: DynestyConfig | None = None,
    slices_rule: str = SLICES_RULE_PER_MODEL,
    hbi_config=None,
    atoms: Sequence[str] = EVIDENCE_CHECK_ATOMS,
    injection_strengths: Mapping[str, float] | None = None,
    rule: EvidenceCheckPassRule | None = None,
    importance_draws: int = DEFAULT_IMPORTANCE_DRAWS,
    rhat_draws_per_run: int = DEFAULT_RHAT_DRAWS_PER_RUN,
    sddr_bootstrap: int = DEFAULT_SDDR_BOOTSTRAP,
) -> dict[str, object]:
    """Run/resume the Phase-3c evidence check and write ``evidence_check_summary.json``.

    Layout: ``null/catalog_XXX/<label>/repeat_YYY`` and
    ``injected/<atom>/<label>/repeat_YYY`` (``<label>`` is ``root`` or the
    atom's mutation id), each fit with a ``fit_summary.json``. The plan
    (``evidence_check_plan.json``) is written or verified before any
    computation; completed runs are reused untouched and interrupted runs
    resume from their dynesty checkpoint.
    """
    root = Path(root)
    atoms = _validated_atoms(atoms)
    survey_config = default_phase3_survey_config() if survey_config is None else survey_config
    dynesty_config = default_phase3_dynesty_config() if dynesty_config is None else dynesty_config
    hbi_config = phase3_hbi_config() if hbi_config is None else hbi_config
    strengths = (
        default_injection_strengths(atoms)
        if injection_strengths is None
        else {str(k): float(v) for k, v in injection_strengths.items()}
    )
    # The expected case counts follow the plan, so a check with fewer catalogs
    # is not failed on the count alone. An explicit rule is honoured but must
    # agree with the plan.
    expected = (int(n_catalogs) * len(atoms), len(atoms))
    if rule is None:
        rule = EvidenceCheckPassRule.for_plan(n_catalogs=int(n_catalogs), n_atoms=len(atoms))
    elif (rule.expected_null_cases, rule.expected_injected_cases) != expected:
        raise ValueError(
            f"the pass rule expects {rule.expected_null_cases} null and "
            f"{rule.expected_injected_cases} injected cases, but this plan produces "
            f"{expected[0]} and {expected[1]}"
        )
    plan = build_evidence_check_plan(
        n_catalogs=n_catalogs,
        root_seed=root_seed,
        repeats=repeats,
        survey_config=survey_config,
        dynesty_config=dynesty_config,
        slices_rule=slices_rule,
        hbi_config=hbi_config,
        atoms=atoms,
        injection_strengths=strengths,
        rule=rule,
        importance_draws=importance_draws,
        rhat_draws_per_run=rhat_draws_per_run,
        sddr_bootstrap=sddr_bootstrap,
    )
    write_or_verify_plan(root / EVIDENCE_CHECK_PLAN_NAME, plan)
    specs = evidence_check_model_specs(atoms)
    configs = {
        label: _model_dynesty_config(
            dynesty_config, int(plan["models"][label]["ndim"]), slices_rule
        )
        for label in specs
    }

    def fit(fit_dir, dataset, label, sampler_seed):
        return _run_fit(
            fit_dir,
            dataset,
            specs[label],
            label=label,
            sampler_seed=sampler_seed,
            repeats=repeats,
            config=configs[label],
            hbi_config=hbi_config,
            importance_draws=importance_draws,
            rhat_draws_per_run=rhat_draws_per_run,
        )

    equivalence = []
    fits = []
    null_cases = []
    injected_cases = []

    for catalog in plan["catalogs"]:
        label = catalog["label"]
        sampler_seed = int(catalog["sampler_seed"])
        dataset, _ = _generate_catalog(int(catalog["data_seed"]), survey_config)
        check = root_equivalence_check(
            dataset.posterior,
            dataset.selection,
            seed=_derived_seed(sampler_seed, "root-equivalence", 0),
        )
        equivalence.append({"catalog": label, **check})
        if not check["passed"]:
            raise RuntimeError(
                f"declarative root and GwcatChiEffBBHModel differ on {label}: {check}"
            )
        base = root / "null" / label
        root_results, root_fit = fit(base / ROOT_LABEL, dataset, ROOT_LABEL, sampler_seed)
        fits.append({"kind": "null", "catalog": label, "label": ROOT_LABEL, "summary": root_fit})
        for atom in atoms:
            child_results, child_fit = fit(base / atom, dataset, atom, sampler_seed)
            fits.append({"kind": "null", "catalog": label, "label": atom, "summary": child_fit})
            null_cases.append(
                _bayes_factor_case(
                    kind="null",
                    catalog=label,
                    atom=atom,
                    root_fit=root_fit,
                    child_fit=child_fit,
                    child_results=child_results,
                    sddr_seed=_derived_seed(sampler_seed, f"evidence-check-sddr:{atom}", 0),
                    sddr_bootstrap=sddr_bootstrap,
                    kappa_hat=rule.sigma_ns_kappa_hat,
                )
            )

    for item in plan["injected"]:
        atom = item["atom"]
        sampler_seed = int(item["sampler_seed"])
        dataset = generate_injected_catalog(
            atom=atom,
            strength=float(item["strength"]),
            data_seed=int(item["data_seed"]),
            survey_config=survey_config,
        )
        check = root_equivalence_check(
            dataset.posterior,
            dataset.selection,
            seed=_derived_seed(sampler_seed, "root-equivalence", 0),
        )
        equivalence.append({"catalog": f"injected/{atom}", **check})
        if not check["passed"]:
            raise RuntimeError(
                f"declarative root and GwcatChiEffBBHModel differ on injected/{atom}: {check}"
            )
        base = root / "injected" / atom
        root_results, root_fit = fit(base / ROOT_LABEL, dataset, ROOT_LABEL, sampler_seed)
        child_results, child_fit = fit(base / atom, dataset, atom, sampler_seed)
        fits.append({"kind": "injected", "catalog": atom, "label": ROOT_LABEL, "summary": root_fit})
        fits.append({"kind": "injected", "catalog": atom, "label": atom, "summary": child_fit})
        injected_cases.append(
            _bayes_factor_case(
                kind="injected",
                catalog=f"injected/{atom}",
                atom=atom,
                root_fit=root_fit,
                child_fit=child_fit,
                child_results=child_results,
                sddr_seed=_derived_seed(sampler_seed, f"evidence-check-sddr:{atom}", 0),
                sddr_bootstrap=sddr_bootstrap,
                kappa_hat=rule.sigma_ns_kappa_hat,
                truth_slope=float(item["strength"]),
            )
        )

    assessments = []
    for item in fits:
        assessment = assess_ns_fit(dict(item["summary"]["fit"]), rule.fit_criteria)
        assessments.append(
            {
                "kind": item["kind"],
                "catalog": item["catalog"],
                "label": item["label"],
                "model_hash": item["summary"]["model_hash"],
                "passed": assessment["passed"],
                "checks": assessment["checks"],
            }
        )
    verdict = evaluate_evidence_check_rule(null_cases, injected_cases, assessments, rule)
    summary = {
        "format_version": EVIDENCE_CHECK_FORMAT_VERSION,
        "plan_sha256": _json_sha256(plan),
        "rule": rule.to_dict(),
        "root_equivalence": equivalence,
        "null_cases": null_cases,
        "injected_cases": injected_cases,
        "fit_assessments": assessments,
        "pass_rule": verdict,
        "evidence_check_passed": verdict["passed"],
    }
    _atomic_write_json(root / EVIDENCE_CHECK_SUMMARY_NAME, summary)
    return summary
